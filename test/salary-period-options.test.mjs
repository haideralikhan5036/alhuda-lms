// Salary period options (Batch C1) tests.
// The reported "only September" symptom is reproduced here as DATA, not
// as a code bug: the live salary_slips table and the teacher blob both
// contain exactly one period (September 2026), and the advance endpoint
// refuses any period without a generated slip (422). So the dropdown
// MUST stay slip-backed. What this batch fixes: (a) the option-building
// logic is extracted into a tested FeeTables helper (same list as
// before, newest first, deduped); (b) the teacher form now explains
// plainly when the current month has no slip yet and what unblocks it;
// (c) the admin payroll month picker is generated, not hardcoded
// (the old list stopped at December 2026 and defaulted to September).
// Run from the repo root:  node test/salary-period-options.test.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const read = (p) => fs.readFileSync(path.join(REPO_ROOT, p), 'utf8');

const results = [];
function check(name, cond, detail = '') {
  results.push({ name, pass: !!cond });
  console.log((cond ? 'PASS' : 'FAIL') + ' | ' + name + (detail && !cond ? ' :: ' + detail : ''));
}

// ---- A) the helper, loaded for real in a vm (same sandbox shape as the
// phase3-fee-salary-read suite) ----
const sandbox = {
  window: {}, console,
  JSON, Object, Array, String, Number, Math, Date, parseFloat, parseInt, isFinite,
};
sandbox.window = sandbox;
sandbox.globalThis = sandbox;
vm.createContext(sandbox);
vm.runInContext(read('js/fee-tables.js'), sandbox);
const FT = sandbox.window.FeeTables;
check('fee-tables exposes periodOptionsForSlips', !!FT && typeof FT.periodOptionsForSlips === 'function');

const S = (month) => ({ month });
if (FT && typeof FT.periodOptionsForSlips === 'function') {
  // 1. The reported symptom, as data: September only in, September only out.
  {
    const opts = FT.periodOptionsForSlips([S('September 2026')]);
    check('September-only slips give exactly one September option',
      opts.length === 1 && opts[0].period === '2026-09' && opts[0].label === 'September 2026', JSON.stringify(opts));
  }
  // 2. Multiple months, newest first, deduped.
  {
    const opts = FT.periodOptionsForSlips([S('September 2026'), S('October 2026'), S('September 2026'), S('August 2026')]);
    check('multiple months: newest first, deduped',
      opts.length === 3 && opts[0].period === '2026-10' && opts[1].period === '2026-09' && opts[2].period === '2026-08', JSON.stringify(opts));
  }
  // 3. Year change: December -> January orders correctly.
  {
    const opts = FT.periodOptionsForSlips([S('December 2026'), S('January 2027')]);
    check('year change orders January 2027 above December 2026',
      opts.length === 2 && opts[0].period === '2027-01' && opts[1].period === '2026-12', JSON.stringify(opts));
  }
  // 4. Unparseable months are skipped, not offered (they would 422).
  {
    const opts = FT.periodOptionsForSlips([S('September 2026'), S(''), S(null), S('TBD'), S('October 2026')]);
    check('unparseable months skipped', opts.length === 2 && opts[0].period === '2026-10', JSON.stringify(opts));
  }
  // 5. Abbreviated month names still parse.
  {
    const opts = FT.periodOptionsForSlips([S('Sep 2026'), S('Oct 2026')]);
    check("abbreviated 'Sep'/'Oct' parse", opts.length === 2 && opts[0].period === '2026-10' && opts[1].period === '2026-09', JSON.stringify(opts));
  }
  // 6. Empty input gives an empty list (the form shows 'No salary record yet').
  {
    const opts = FT.periodOptionsForSlips([]);
    check('empty slips give empty options', opts.length === 0, JSON.stringify(opts));
  }
}

// ---- B) structural: teacher form + admin picker ----
const TEACHER = read('teacher.html');
check('teacher form uses the shared periodOptionsForSlips helper',
  TEACHER.includes('window.FeeTables.periodOptionsForSlips'));
check('teacher form has the current-month-missing note element',
  TEACHER.includes('id="tAdvPeriodNote"'));
check('teacher form explains the missing-slip reason in plain words',
  TEACHER.includes('No slip has been generated for') && TEACHER.includes('you can still request an advance for it below (custom amount only)'));
const INDEX = read('index.html');
const selStart = INDEX.indexOf('id="salaryMonthSelect"');
const selEnd = INDEX.indexOf('</select>', selStart);
const selBlock = selStart >= 0 ? INDEX.slice(selStart, selEnd) : '';
check('admin payroll month picker has no hardcoded options',
  selStart >= 0 && !selBlock.includes('<option'));
check('admin payroll month picker is generated by script (12 back, 2 forward, current selected)',
  INDEX.includes('Batch C1: payroll month options are generated') && INDEX.includes('off = -12; off <= 2; off++') && INDEX.includes('if (off === 0) opt.selected = true'));

const failed = results.filter(r => !r.pass);
console.log(`\n${results.length - failed.length}/${results.length} checks passed`);
if (failed.length) { console.log('FAILED: ' + failed.map(f => f.name).join('; ')); process.exit(1); }
